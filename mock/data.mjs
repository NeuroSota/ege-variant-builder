const MODIFIERS = [
  "с отбором", "на клетчатой бумаге", "по готовому чертежу", "с доказательством", "обратная задача",
  "с несколькими случаями", "по источнику ФИПИ", "с вычислением площади", "с параметризацией",
  "с оценкой", "через подобие", "координатным методом", "с дробными данными", "с модулем",
];

export function buildCatalog(seed = 2027) {
  const r = rng(seed);
  const tasks = LINES.map(([number, title, points, topics, count, expShare]) => {
    const types = [];
    for (let i = 0; i < count; i++) {
      const topic = topics[i % topics.length];
      const modifier = pick(r, MODIFIERS);
      const experimental = r() < expShare;
      types.push({
        id: `t${number}_${String(i + 1).padStart(3, "0")}`,
        number,
        topic,
        title: experimental
          ? `Экспериментальное задание по источнику №${int(r, 400000, 520000)} — проверка учителем`
          : `${topic}: ${modifier}${i >= topics.length ? ` (вариант ${Math.floor(i / topics.length) + 1})` : ""}`,
        experimental,
        // Доля задания в реальных экзаменах: интерфейсу пригодится для сортировки.
        frequency: experimental ? "rare" : pick(r, ["often", "often", "sometimes", "rare"]),
      });
    }
    return { number, title, part: number <= 12 ? 1 : 2, points, types };
  });
  return { exam: "ЕГЭ по математике (профильный уровень)", year: 2027, tasks };
}

const LONG_FORMULA =
  "\\frac{\\sqrt{3}\\sin^{2}\\left(\\frac{7\\pi}{12}-x\\right)+\\log_{\\frac{1}{3}}\\left(x^{2}-4x+5\\right)" +
  "-\\frac{2^{x+1}-3\\cdot 4^{x-\\frac{1}{2}}}{\\cos\\left(2x-\\frac{\\pi}{3}\\right)+\\operatorname{tg}^{2}x}}" +
  "{\\left|x-\\sqrt{2}\\right|+\\left|x+\\sqrt{2}\\right|-\\sqrt[3]{x^{3}-27}}=\\frac{1}{2}";

export function buildTaskContent(type, r) {
  const number = type.number;
  const a = int(r, 2, 9);
  const b = int(r, 2, 9);
  const long = r() < 0.06;
  const withImage = [1, 3, 8, 11, 14, 17].includes(number) && r() < 0.8;
  let statement;
  let answer;
  let solution;
  if (number <= 12) {
    statement = long
      ? `Найдите корень уравнения $$${LONG_FORMULA}$$ на промежутке $[-${a};\\ ${b}]$.`
      : `В задаче «${type.title}» дано: $a=${a}$, $b=${b}$. Найдите значение выражения $\\frac{a^{2}+b^{2}}{a+b}$, округлив до сотых.`;
    answer = ((a * a + b * b) / (a + b)).toFixed(2).replace(".", ",");
    solution = `$\\frac{${a}^{2}+${b}^{2}}{${a}+${b}}=\\frac{${a * a + b * b}}{${a + b}}\\approx ${answer}$.`;
  } else {
    statement =
      `а) ${long ? `Решите уравнение $$${LONG_FORMULA}$$` : `Решите уравнение $${a}\\sin^{2}x-${b}\\sin x\\cos x=0$`}.\n` +
      `б) Укажите корни этого уравнения, принадлежащие отрезку $\\left[-\\frac{${a}\\pi}{2};\\ -\\pi\\right]$.`;
    answer = `а) $\\pi k$; $\\operatorname{arctg}\\frac{${b}}{${a}}+\\pi k$, $k\\in\\mathbb{Z}$; б) $-2\\pi$, $-\\pi$`;
    solution =
      `Вынесем $\\sin x$: $\\sin x\\,(${a}\\sin x-${b}\\cos x)=0$. ` +
      `Либо $\\sin x=0$, либо $\\operatorname{tg}x=\\frac{${b}}{${a}}$. ` +
      `Отбор корней на отрезке выполним с помощью единичной окружности.`;
  }
  return { statement, answer, solution, withImage };
}

export function drawingSvg(seed) {
  const r = rng(seed);
  const pts = Array.from({ length: 3 + Math.floor(r() * 3) }, () => [20 + r() * 260, 20 + r() * 160]);
  const labels = "ABCDEF";
  const poly = pts.map((p) => p.join(",")).join(" ");
  const text = pts
    .map((p, i) => `<text x="${p[0] + 4}" y="${p[1] - 4}" font-family="sans-serif" font-size="14">${labels[i]}</text>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="300" height="200" viewBox="0 0 300 200">` +
    `<rect width="300" height="200" fill="white"/><polygon points="${poly}" fill="none" stroke="black" stroke-width="2"/>${text}</svg>`;
}
